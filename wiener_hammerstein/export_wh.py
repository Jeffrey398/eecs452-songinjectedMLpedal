import json
import math
from pathlib import Path

MODEL_DIR = Path(__file__).resolve().parent
OUTPUT_FILE = MODEL_DIR / "bluesdriver_wh_params.h"

PARAMETER_NAMES = [
    "pre_hp",
    "pre_lp",
    "gain",
    "bias",
    "post_lp",
    "output_gain",
]


def load_models():
    models = []

    for g in range(6):
        row = []

        for t in range(6):
            path = MODEL_DIR / f"bluesdriver_wh_g{g}_t{t}.json"

            if not path.exists():
                raise FileNotFoundError(path)

            with path.open() as f:
                data = json.load(f)

            if data["sample_rate"] != 48000:
                raise ValueError(f"Invalid sample rate: {path}")

            if not math.isclose(data["drive"], g / 5):
                raise ValueError(f"Incorrect drive setting: {path}")

            if not math.isclose(data["tone"], t / 5):
                raise ValueError(f"Incorrect tone setting: {path}")

            params = [
                float(data["parameters"][name])
                for name in PARAMETER_NAMES
            ]

            if not all(math.isfinite(p) for p in params):
                raise ValueError(f"Invalid parameters: {path}")

            row.append(params)

            print(
                f"Loaded G{g} T{t} | "
                f"ESR={data['test_esr'] * 100:.2f}% | "
                f"Converged={data['optimizer_success']}"
            )

        models.append(row)

    return models


def export_header(models):
    lines = [
        "#pragma once",
        "",
        "// Automatically generated by export_wh.py",
        "// Boss Blues Driver Wiener-Hammerstein models",
        "// Sample rate: 48000 Hz",
        "",
        "struct WHParams",
        "{",
        "    float pre_hp;",
        "    float pre_lp;",
        "    float gain;",
        "    float bias;",
        "    float post_lp;",
        "    float output_gain;",
        "};",
        "",
        "// First index: Drive (0, 20, 40, 60, 80, 100%)",
        "// Second index: Tone (0, 20, 40, 60, 80, 100%)",
        "",
        "static constexpr WHParams BLUESDRIVER_WH[6][6] =",
        "{",
    ]

    for g, row in enumerate(models):
        lines.append(f"    {{ // Drive = {g / 5:.2f}")

        for t, params in enumerate(row):
            values = ", ".join(f"{p:.9e}f" for p in params)

            lines.append(
                f"        {{{values}}}, // Tone = {t / 5:.2f}"
            )

        lines.append("    },")

    lines.extend(["};", ""])

    OUTPUT_FILE.write_text("\n".join(lines))

    print("\nExport complete")
    print(f"Models exported: {len(models) * 6}")
    print(f"Total parameters: {len(models) * 6 * 6}")
    print(f"Saved: {OUTPUT_FILE}")


def main():
    models = load_models()
    export_header(models)


if __name__ == "__main__":
    main()
